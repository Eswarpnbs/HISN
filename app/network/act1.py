"""Generate data-driven network injects from the empirical RLF profile (fixed seed, reproducible)."""
import random, yaml

def network_inject(condition="rainy", profile_path="kb/rulepacks/network_profile.yaml", links_per_district=400,
                   days=3, seed=42, districts=("D1", "D2", "D3", "D4", "D5"), t0=1):
    prof = yaml.safe_load(open(profile_path, encoding="utf-8"))
    p = prof[f"p_rlf_{condition}"]; rng = random.Random(seed)
    out_min = prof.get("median_outage_minutes_on_failure_days") or 10
    events, total = [], 0
    for i, d in enumerate(districts):
        failed = sum(1 for _ in range(links_per_district * days) if rng.random() < p)
        total += failed
        if failed:
            events.append({"id": f"RLF-{condition.upper()}-{d}", "t": t0 + i, "act": 1, "kind": "network_kpi",
                           "audience": ["network_ai"],
                           "payload": {"district": d, "backhaul_link_failures": failed, "days": days,
                                       "median_outage_min": out_min, "condition": condition,
                                       "p_rlf_per_link_day": p, "source": "empirical RLF profile (proxy data)"}})
    events.append({"id": f"RLF-{condition.upper()}-SUM", "t": t0 + 15, "act": 1, "kind": "network_summary",
                   "audience": ["tdra"],
                   "payload": {"summary": f"{total} backhaul link failures expected over {days} {condition} days",
                               "basis": f"measured {condition}-day failure rate {p} per link-day (proxy data)",
                               "delayed_by_min": 15}})
    return {"note": f"Generated by app/network/act1.py ({condition}, seed {seed})", "events": events}, total
