"""Export HISN results into ITU AI Readiness Simulation Game formats (decisions, delegate narrative, causal preview)."""
import datetime, json, os, sys, pathlib, yaml
from pathlib import Path

ITU = pathlib.Path(os.environ.get("ITU_DIR", pathlib.Path.home() / "ITUAIReadiness/simulation"))
sys.path.insert(0, str(ITU))
from server.game.causal_graph import CausalGraph

OUT = Path("docs/itu_export"); OUT.mkdir(parents=True, exist_ok=True)
# Readiness dimensions each candidate provision touches (official IDs from dimensions.json)
PATCH_DIMS = {"P-AUTH": [10, 13], "P-ROUTE": [10, 13], "P-FRAUD": [10], "P-VERIFIED": [10, 13]}

def jl(p):
    p = Path(p)
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []

decisions = []
for r in jl("runs/signoffs.jsonl"):
    if r.get("kind") != "human_signoff": continue
    dims = sorted({d for pid in r["patches"] for d in PATCH_DIMS.get(pid, [10])})
    decisions.append({
        "id": f"hisn-{r['at']}", "session_id": "hisn-export", "delegate_id": "team-sankalp",
        "country_name": "United Arab Emirates",
        "decision_text": (f"{r['decision']}: candidate provision(s) {'+'.join(r['patches'])} for governing AI SMS filters "
                          f"that affect essential health and government messages (simulation; comparators pending verification)."),
        "affected_dimensions": ",".join(map(str, dims)), "timestamp": r["at"], "applied": False,
        "hisn_evidence": r["evidence"], "hisn_officer": f"{r['officer']} ({r['officer_role']})"})
(OUT / "decisions.json").write_text(json.dumps(decisions, indent=2, ensure_ascii=False), encoding="utf-8")

gaps = yaml.safe_load(open("docs/gap_register.yaml", encoding="utf-8"))
hn = Path("docs/headline_numbers.md").read_text(encoding="utf-8") if Path("docs/headline_numbers.md").exists() else ""
narr = ["# Delegate narrative - United Arab Emirates (generated by HISN for the ITU AI Readiness Simulation Game)", "",
        "Domain: governance of AI systems in telecom networks that decide whether essential health and government "
        "messages reach citizens (AI SMS filtering, network AI failover).", "",
        "D10 AI & Policies: binding instruments exist for health-data localisation (Federal Law No. 2 of 2019, Art. 13) and "
        "operator spam duties (TDRA Unsolicited Electronic Communications Policy v1.1), but filtering duties cover marketing "
        "spam rather than fraud, and no instrument assigns authority over operators' AI filter changes.", "",
        "D13 Digital Infrastructure: sender identity is not authenticated end-to-end; a policy sandbox shows sender "
        "authentication plus a verified-sender lane would raise protection and access together.", "", "Identified gaps:"]
narr += [f"- {g['id']}: {g['title']} ({g['status']})" for g in gaps]
narr += ["", "Measured results (synthetic sandbox): see docs/headline_numbers.md in the HISN repository."]
(OUT / "delegate_narrative_uae.md").write_text("\n".join(narr) + "\n", encoding="utf-8")

cg = CausalGraph()
effects = cg.propagate({10: 1.0})
preview = {"note": "Unit impulse on D10 through ITU's CausalGraph: shows WHICH dimensions are reached, not a predicted score change.",
           "source": "server/game/causal_graph.py (ITU reference code, unmodified)",
           "downstream_from_D10": {str(k): round(v, 3) for k, v in sorted(effects.items()) if k != 10}}
(OUT / "causal_preview.json").write_text(json.dumps(preview, indent=2), encoding="utf-8")
print(f"decisions: {len(decisions)} | narrative: {len(gaps)} gaps | ITU causal graph D10 reaches: {preview['downstream_from_D10']}")
print(f"written {OUT}/decisions.json, delegate_narrative_uae.md, causal_preview.json ({datetime.date.today()})")
