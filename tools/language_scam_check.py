"""Does English-only content scoring let non-English scams through? The same scam in English and Arabic, run through
HISN's UAE firewall under four conditions. Synthetic, fictional senders, reserved .example domains. Standalone: does not
affect the pre-registered evaluation."""
import copy, sys, yaml
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.audit import AuditLog
from app.core.firewall import SmsFirewall
from app.core.packs import pack

from app.core.fairness import SCAM_PAIRS as SCAMS  # single source, shared with the deployment gate

def run(log=Path("runs/language_scam_check.jsonl")):
    log.parent.mkdir(exist_ok=True); log.unlink(missing_ok=True); a = AuditLog(log)
    p = pack("UAE"); adopted = yaml.safe_load(open("kb/rulepacks/uae/adopted.yaml", encoding="utf-8"))["flags"]
    conds = [("Current rules, normal", p["firewall_flags"], None), ("Current rules, after panic (0.20)", p["firewall_flags"], 0.2),
             ("Current rules, after drift (0.15)", p["firewall_flags"], 0.15), ("Tested rule set, after panic (0.20)", adopted, 0.2)]
    rows = []
    for name, base, en, ar in SCAMS:
        for cname, flags, thr in conds:
            res = {}
            for lang, text in (("en", en), ("ar", ar)):
                fw = SmsFirewall(p["senders"], a, policy=flags)
                if thr is not None: fw.set_threshold(thr, "language what-if")
                res[lang] = (fw.process({**copy.deepcopy(base), "short_message": text}, now=0) or {}).get("action", "?")
            rows.append({"scam": name, "condition": cname, **res,
                         "arabic_slips_through": res["ar"] == "ALLOW" and res["en"] != "ALLOW"})
    a.write({"kind": "language_scam_check", "rows": rows})
    return {"rows": rows, "slips": sum(r["arabic_slips_through"] for r in rows), "audit_ok": a.verify()}

def main():
    r = run()
    L = ["# Does English-only content scoring let Arabic scams through?", "",
         "_The same scam in English and Arabic through HISN's UAE firewall. Synthetic, fictional senders, reserved .example domains._", "",
         "| Scam | Condition | English | Arabic | Arabic slips through? |", "|---|---|---|---|---|"]
    L += [f"| {x['scam']} | {x['condition']} | {x['en']} | {x['ar']} | {'**YES**' if x['arabic_slips_through'] else 'no'} |" for x in r["rows"]]
    L += ["", f"**Arabic scams delivered where the English version was stopped: {r['slips']} of {len(r['rows'])} cases.**", "",
          ("The language blind spot cuts both ways: content scoring that reads only English over-blocks genuine English messages "
           "(see docs/fairness_check.md) and under-blocks scams written in other languages." if r["slips"] else
           "In these cases the Arabic scams were stopped by non-content signals (route, link, sender), so the blind spot did not let them through."),
          "", f"_Audit chain verified: {r['audit_ok']}. Generated by tools/language_scam_check.py._"]
    Path("docs/language_scam_check.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L)); print("\nwritten docs/language_scam_check.md")

if __name__ == "__main__":
    main()
