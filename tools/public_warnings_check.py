"""Public-warning test set (pre-registered): synthetic messages modelled on scams UAE authorities warned about, in English
and Arabic, through HISN's UAE firewall. Expected outcomes were fixed before running: scams not delivered, genuine not lost."""
import sys, yaml
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.audit import AuditLog
from app.core.firewall import SmsFirewall
from app.core.packs import pack

def run(log=Path("runs/public_warnings.jsonl")):
    items = yaml.safe_load(open("scenarios/public_warnings.yaml", encoding="utf-8"))["items"]
    log.parent.mkdir(exist_ok=True); log.unlink(missing_ok=True); a = AuditLog(log)
    p = pack("UAE"); adopted = yaml.safe_load(open("kb/rulepacks/uae/adopted.yaml", encoding="utf-8"))["flags"]
    conds = [("Current rules, normal", p["firewall_flags"], None), ("Current rules, after panic (0.20)", p["firewall_flags"], 0.2),
             ("Tested rule set, after panic (0.20)", adopted, 0.2)]
    rows = []
    for it in items:
        base = {"source_addr": it["claims"], "route": it["route"]}
        if it.get("authenticated"): base["authenticated"] = True
        if it.get("priority"): base["priority"] = it["priority"]
        for cname, flags, thr in conds:
            for lang in ("en", "ar"):
                fw = SmsFirewall(p["senders"], a, policy=flags)
                if thr is not None: fw.set_threshold(thr, "public-warning test")
                o = fw.process({**base, "short_message": it[lang]}, now=0) or {}
                act = o.get("action", "?")
                ok = (act != "ALLOW") if it["label"] == "scam" else not (act.startswith("BLOCK") or o.get("silent_drop"))
                rows.append({"id": it["id"], "label": it["label"], "condition": cname, "lang": lang, "action": act, "meets_expectation": ok})
    a.write({"kind": "public_warnings_check", "rows": rows})
    return {"rows": rows, "audit_ok": a.verify()}

def main():
    r = run(); rows = r["rows"]
    conds = list(dict.fromkeys(x["condition"] for x in rows))
    L = ["# Public-warning test set (pre-registered)", "",
         "_Synthetic messages modelled on scams that UAE authorities publicly warned about (sources in scenarios/public_warnings.yaml), "
         "in English and Arabic. Expected outcomes fixed before running: scams not delivered; genuine messages not lost._", "",
         "| Condition | Scams stopped | Genuine not lost | Meets expectation |", "|---|---|---|---|"]
    for c in conds:
        cs = [x for x in rows if x["condition"] == c]
        sc = [x for x in cs if x["label"] == "scam"]; gn = [x for x in cs if x["label"] == "genuine"]
        L.append(f"| {c} | {sum(x['action'] != 'ALLOW' for x in sc)}/{len(sc)} | {sum(x['meets_expectation'] for x in gn)}/{len(gn)} | "
                 f"**{sum(x['meets_expectation'] for x in cs)}/{len(cs)}** |")
    L += ["", "## Every message", "", "| Item | Expected | " + " | ".join(f"{c} (EN / AR)" for c in conds) + " |", "|---|---|" + "---|" * len(conds)]
    for iid in dict.fromkeys(x["id"] for x in rows):
        xs = [x for x in rows if x["id"] == iid]
        cell = lambda c: " / ".join(("" if y["meets_expectation"] else "**") + y["action"] + ("" if y["meets_expectation"] else "**")
                                    for y in xs if y["condition"] == c)
        L.append(f"| {iid} | {'not delivered' if xs[0]['label'] == 'scam' else 'not lost'} | " + " | ".join(cell(c) for c in conds) + " |")
    L += ["", "Bold = did not meet the pre-registered expectation.", "", f"_Audit chain verified: {r['audit_ok']}. Generated by tools/public_warnings_check.py._"]
    Path("docs/public_warnings.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L)); print("\nwritten docs/public_warnings.md")

if __name__ == "__main__":
    main()
