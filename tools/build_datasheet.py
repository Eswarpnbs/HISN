"""Datasheet for the HISN synthetic SMS dataset (Gebru et al., "Datasheets for Datasets"; ITU AI Readiness Report 2.0
data metrics). Every figure is computed from the published files. Also checks that no URL points to a real domain."""
import csv, re, sys, yaml
from collections import Counter
from pathlib import Path

csv_path = next(Path(".").glob("**/hisn_synthetic_sms.csv"), None)
if csv_path is None or ".venv" in str(csv_path):
    sys.exit("hisn_synthetic_sms.csv not found: run python build_dataset.py first")
rows = list(csv.DictReader(open(csv_path, encoding="utf-8")))
meta_path = csv_path.parent / "metadata" / "metadata.yaml"
meta = yaml.safe_load(open(meta_path, encoding="utf-8")) if meta_path.exists() else {}
cols = list(rows[0])
small = {c: Counter(r[c] for r in rows) for c in cols if 1 < len({r[c] for r in rows}) <= 12}
urls = [u for r in rows for v in r.values() for u in re.findall(r"https?://[^\s\"']+", v or "")]
hosts = [re.sub(r"^https?://", "", u).split("/")[0].lower() for u in urls]
unsafe = sorted({h for h in hosts if not h.endswith((".example", ".test", ".invalid", "example.com", "example.org"))})

L = [f"# Datasheet: {meta.get('name', 'HISN synthetic SMS dataset')}", "",
     f"_Generated from `{csv_path}` by `tools/build_datasheet.py`. Structure follows Gebru et al., Datasheets for Datasets; "
     "metrics follow the ITU AI Readiness Report 2.0 data dimension._", "",
     "## Motivation",
     "Built to evaluate governance of telecom SMS filtering for essential health and government messages, and published because "
     "ITU's sandbox datasets contain no SMS scam data. Created by Team Sankalp for the ITU AI for Good Lab Hackathon (UAE).", "",
     "## Composition",
     f"- Rows: {len(rows)}; columns: {', '.join(cols)}"]
L += [f"- `{c}`: " + ", ".join(f"{k} ({v})" for k, v in cnt.most_common()) for c, cnt in small.items()]
L += ["", "## Collection and labelling",
      "- Fully synthetic: written for the scenario, no real messages, senders or people. Labels assigned by construction.",
      "- Fictional senders only; no real phishing content is generated.",
      f"- URL safety check: {len(urls)} URL(s) found; non-reserved domains: {', '.join(unsafe) if unsafe else 'none'}.", "",
      "## ITU AI Readiness Report 2.0 data metrics",
      "| Metric | Value |", "|---|---|",
      "| Local data share (local vs synthetic) | 0% local; 100% synthetic (stated openly) |",
      "| Availability of labelled data | 100% labelled by construction |",
      "| Bias documentation | Synthetic; English-centred text; language-fairness findings in docs/fairness_check.md |",
      "| Provenance and transparency | Generated by build_dataset.py; SHA-256 in metadata |",
      f"| Licence | {meta.get('licence', 'CC-BY-4.0')} |", "",
      "## Uses",
      "- Intended: testing governance of SMS filters (holds, escalation, fairness, rule testing) in a sandbox.",
      "- Not intended: training production spam filters, or any claim about real-world message volumes or accuracy.", "",
      "## Distribution and maintenance",
      f"- Licence {meta.get('licence', 'CC-BY-4.0')}; distributed with the HISN repository. Maintained by Team Sankalp (eswarpnbs@gmail.com)."]
text = "\n".join(L) + "\n"
for out in (Path("docs/datasheet_sms_dataset.md"), csv_path.parent / "DATASHEET.md"):
    out.write_text(text, encoding="utf-8")
print(text); print("written docs/datasheet_sms_dataset.md and", csv_path.parent / "DATASHEET.md")
if unsafe:
    sys.exit(f"WARNING: non-reserved URL domains found: {unsafe}")
